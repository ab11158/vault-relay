async function confirm(h,publicId){
  const modal=v71.settings.open(h.p);
  const row=modal.contentEl.querySelectorAll('.vr71-device-row').find(item=>item.querySelectorAll('input').some(x=>x.value===publicId));
  const pending=row.querySelectorAll('button').find(x=>x.textContent==='确认信任');
  await pending.click();
  const dialog=h.p.app.openedModals.at(-1);
  assert.equal(dialog.contentEl.querySelector('textarea').value,publicId);
  await button(dialog,'确认信任').click();
  assert.equal(dialog.closed,true,dialog.contentEl.textContent);
  return modal;
}
async function packet(h,paths){
  const q=await h.p.engine.previewUpload();
  const options={selectedPaths:paths,expectedFingerprint:q.fingerprint,allowInitial:true};
  const native=h.p.engine.safeUpload?await h.p.engine.safeUpload(options):await h.p.engine.safeExport(q,options);
  const result=await h.p.finalizeConfirmedUpload(native);
  const rec=h.p.data.bundleRecords.at(-1);
  assert.equal(rec.stored.path,result.packageResult.path);
  return {rec,bytes:await h.adapter.readBinary(rec.stored.path)};
}
