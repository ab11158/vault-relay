'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {host,publish,receive,Windows,Mobile,A,B,results}=require('./test-flow.cjs');
const find=(el,selector,text)=>el.querySelectorAll(selector).find(x=>x.textContent===text);
const button=(el,text)=>{const node=find(el,'button',text);assert(node,'Missing '+text);return node;};
const click=async el=>{assert(!el.hidden&&!el.disabled);await el.handlers.click({preventDefault(){},stopPropagation(){}});};
const footers=el=>el.querySelectorAll('.vr609-actions');
const selectedRadio=(el,name)=>{const radio=el.querySelectorAll('input').find(x=>x.getAttribute('aria-label')==='选择 '+name);assert(radio);radio.checked=true;radio.handlers.change();};
const checkbox=(el,name)=>{const input=el.querySelectorAll('input').find(x=>x.getAttribute('aria-label')==='选择 '+name);assert(input,'Missing checkbox '+name);return input;};
const selectCheckbox=(input,value,modifiers={})=>{input.handlers.click(modifiers);input.checked=value;input.handlers.change();};
const settle=async test=>{for(let i=0;i<50;i++){if(test())return;await new Promise(resolve=>setTimeout(resolve,10));}assert(test(),'UI did not update');};
const checkedPlan=async h=>{await h.p.v604PrepareInbox();return h.p.engine.latestPlan();};
const apply=(h,plan,paths)=>h.p.engine.applyPlan?h.p.engine.applyPlan(plan,{selectedReviewPaths:paths}):h.p.engine.safeApply(plan,{selectedReviewPaths:paths});
const activeZip=async(h,packet)=>{
  const row=(h.p._v604InboxRows||[]).find(x=>x.sha256===packet.rec.sha256);
  return row&&await h.adapter.exists(row.path)?row.path:null;
};
const packetDoc=packet=>JSON.parse(Buffer.from(Windows.__testing.tools.zipDecode(packet.bytes).get('sync-inventory.json')).toString('utf8'));
async function openReview(h){
  h.p.openCoreUi('download');const dialog=h.p.app.openedModals.at(-1);
  try{await h.p._v602ReviewReady;}catch(error){throw Error(dialog.contentEl.textContent,{cause:error});}
  return dialog;
}
async function discardScenario(fromType,toType,fromID,toID){
  const source=await host(fromType,fromID,'Source'),target=await host(toType,toID,'Target');
  await source.write('Diverged.md','[title]\nchange remote\nunchanged line');await source.write('New.md','extra');
  const packet=await publish(source);
  await target.write('Diverged.md','local');
  await receive(target,packet,false);
  const before=await checkedPlan(target),old=before.items.find(x=>x.path==='Diverged.md');
  assert.equal(old.status,'conflict');
  await target.write('Diverged.md','[title]\nchange local\nunchanged line\nremove this line');
  await assert.rejects(()=>target.p.v608DiscardReviewVersion(before,old.recordId,old.version),/重新审核/);
  const review=await openReview(target),content=review.contentEl;
  const [normal,pending]=footers(content);
  assert(!normal.hidden&&pending.hidden);
  assert(!button(normal,'预览确认处理（1）').hidden);
  await click(button(content,'待处理 1'));
  assert(normal.hidden&&!pending.hidden);
  assert(button(normal,'预览确认处理（1）').hidden);
  assert(button(pending,'本次忽略').disabled);
  selectedRadio(content,'Diverged.md');
  const view=button(pending,'查看原文');assert(!view.hidden);
  global.document={createElement:tag=>Object.assign(new review.modalEl.constructor(tag),{dataset:{}})};
  try{
    await click(view);
    const diff=target.p.app.openedModals.at(-1);await diff.opened;
    const columns=diff.contentEl.querySelectorAll('pre');
    assert.equal(columns.length,2);
    assert(columns[0].textContent.includes('[title]')&&columns[1].textContent.includes('[title]'));
    assert.equal(columns[0].querySelector('del').textContent,'remove this line');
    assert(columns[1].querySelectorAll('span').some(x=>x.textContent==='remote'&&x.className==='vru-conflict-change'));
    assert.equal(await target.adapter.read('Diverged.md'),'[title]\nchange local\nunchanged line\nremove this line');
    diff.close();
  }finally{delete global.document;}
  assert(!button(pending,'取消导入').hidden);
  assert(button(pending,'打开同步空间').hidden);
  const conflictSection=content.querySelectorAll('.vr607-review-section').find(row=>row.querySelector('.vr607-file-title').textContent==='Diverged.md');
  const conflictDetails=find(conflictSection,'summary','详细内容').parentNode;
  assert(!conflictDetails.open);
  for(const label of ['查看原文','导入','备份导入','取消导入'])assert(button(conflictDetails,label));
  await click(button(pending,'本次忽略'));
  assert(button(content,'待处理 0'));assert(!target.p.data.v608DiscardedVersions);
  await click(button(content,'显示已忽略（1）'));
  assert(normal.hidden&&pending.hidden);
  await click(button(content,'恢复显示'));
  assert(button(content,'待处理 1'));
  await click(button(content,'可导入 1'));
  assert(!normal.hidden&&pending.hidden);
  assert(!button(normal,'预览确认处理（1）').disabled);
  await click(button(content,'待处理 1'));
  await click(button(content,'本次忽略'));review.close();
  const reopened=await openReview(target),newContent=reopened.contentEl;
  await click(button(newContent,'待处理 1'));
  selectedRadio(newContent,'Diverged.md');
  await click(button(footers(newContent)[1],'取消导入'));
  await click(button(target.p.app.openedModals.at(-1).contentEl,'返回审核'));
  assert(!target.p.data.v608DiscardedVersions);
  await click(button(newContent,'取消导入'));
  await click(button(target.p.app.openedModals.at(-1).contentEl,'确认取消导入'));
  assert.equal(Object.keys(target.p.data.v608DiscardedVersions).length,1);
  assert(button(newContent,'待处理 0'));assert(button(newContent,'已跳过 1'));
  assert.equal(await target.adapter.read('Diverged.md'),'[title]\nchange local\nunchanged line\nremove this line');
  assert(await activeZip(target,packet));
  target.p=await target.restart();
  const after=await checkedPlan(target);
  assert.equal(after.items.find(x=>x.path==='Diverged.md').status,'discarded');
  assert.equal(after.items.find(x=>x.path==='New.md').status,'create');
  assert.equal((await apply(target,after,['New.md'])).created,1);
  assert.equal(await target.adapter.read('Diverged.md'),'[title]\nchange local\nunchanged line\nremove this line');
  assert.equal(await target.adapter.read('New.md'),'extra');
  assert(!target.p.v605HasPending());
  assert(!await target.adapter.exists('VaultRelay-Transfer/inbox/'+packet.rec.name));
  await receive(target,packet,false);
  assert(!target.p.v605HasPending());
  assert.equal(Object.keys(target.p.data.v608DiscardedVersions).length,1);
  const next=await target.p.engine.latestPlan();
  assert(!next.items.some(item=>item.version?.versionId===old.version.versionId));
  assert.equal(await target.adapter.read('Diverged.md'),'[title]\nchange local\nunchanged line\nremove this line');
}
async function run(){
  await discardScenario(Windows,Mobile,A,B);
  await discardScenario(Mobile,Windows,B,A);
  const source=await host(Windows,A,'Early'),target=await host(Mobile,B,'Late');
  await source.write('OldV.md','old');await source.write('OldOnly.md','missing');
  const early=await publish(source);
  await source.write('OldV.md','latest');await source.write('SamePath.md','remote');
  const late=await publish(source);
  const stage=await host(Mobile,B,'No early package');
  await receive(stage,late,false);
  const missing=await openReview(stage),reviewContent=missing.contentEl;
  await settle(()=>find(reviewContent,'button','待处理 1'));
  await click(button(reviewContent,'待处理 1'));
  const fileSection=reviewContent.querySelectorAll('.vr607-review-section').find(row=>row.querySelector('.vr607-file-title').textContent==='OldOnly.md');
  const row=find(fileSection,'summary','详细内容').parentNode;
  assert(button(row,'打开同步空间'));assert(button(row,'本次忽略'));
  assert(!find(row,'button','取消导入'));
  const [importFooter,missingFooter]=footers(reviewContent);
  assert(importFooter.hidden&&!missingFooter.hidden);
  const pendingAll=reviewContent.querySelectorAll('.vr607-tools')[0].querySelectorAll('input')[0];
  assert(!pendingAll.hidden&&!pendingAll.disabled);
  const pendingItems=reviewContent.querySelectorAll('input').filter(x=>(x.getAttribute('aria-label')||'').startsWith('选择 '));
  assert(pendingItems.length>=1);
  pendingAll.checked=true;pendingAll.onchange();
  assert(pendingItems.every(x=>x.checked));
  pendingAll.checked=false;pendingAll.onchange();
  assert(pendingItems.every(x=>!x.checked));
  assert(!button(missingFooter,'打开同步空间').hidden);
  const panel=Mobile.__testing.panel.prototype,previousOpen=panel.openSyncSpaceBrowser;
  let opened=0;
  panel.openSyncSpaceBrowser=()=>opened++;
  try{await click(button(missingFooter,'打开同步空间'));assert.equal(opened,1);}
  finally{panel.openSyncSpaceBrowser=previousOpen;}
  selectedRadio(reviewContent,'OldOnly.md');
  assert(button(missingFooter,'取消导入').hidden);
  await click(button(missingFooter,'本次忽略'));
  assert(button(reviewContent,'待处理 0'));
  assert(await activeZip(stage,late));
  await receive(target,late);await receive(target,early,false);
  const view=await openReview(target),content=view.contentEl;
  assert(button(content,'待处理 0'));assert(button(content,'已跳过 1'));
  await click(button(content,'已跳过 1'));
  const skipped=checkbox(content,'OldV.md');
  assert(!skipped.checked);
  const toolbar=content.querySelectorAll('.vr607-tools')[0];
  const selectAll=toolbar.querySelectorAll('input')[0];
  assert(!selectAll.hidden&&!selectAll.disabled);
  selectAll.checked=true;selectAll.onchange();
  assert(checkbox(content,'OldV.md').checked);
  selectAll.checked=false;selectAll.onchange();
  assert(!checkbox(content,'OldV.md').checked);
  selectCheckbox(skipped,true);assert(checkbox(content,'OldV.md').checked);
  selectCheckbox(checkbox(content,'OldV.md'),false);assert(!checkbox(content,'OldV.md').checked);
  selectCheckbox(checkbox(content,'OldV.md'),true);
  const confirmSkip=content.querySelectorAll('button').find(x=>x.textContent==='确认跳过（1）');
  assert(confirmSkip&&!confirmSkip.hidden&&!confirmSkip.disabled);
  await click(confirmSkip);
  await click(button(target.p.app.openedModals.at(-1).contentEl,'确认跳过所选版本'));
  assert(button(content,'已跳过 0'));
  target.p=await target.restart();
  const reopenedSkip=await openReview(target),reopenedContent=reopenedSkip.contentEl;
  assert(reopenedContent.textContent.includes('已跳过 0'));
  assert(!reopenedContent.textContent.includes('OldV.md'));
  assert.equal(Object.keys(target.p.data.v610ConfirmedSkips).length,1);
  new Mobile.__testing.panel(target.p.app,target.p).showV606Comparison(packetDoc(early));
  const resumedComparison=target.p.app.openedModals.at(-1);await resumedComparison.opened;
  assert(resumedComparison.contentEl.textContent.includes('本机 Red1 · 对端 Win1'));
  assert(!resumedComparison.contentEl.textContent.includes('OldV.md'));
  assert.equal(await target.adapter.read('OldV.md'),'latest');
  await stage.write('SamePath.md','local');
  new Mobile.__testing.panel(stage.p.app,stage.p).showV606Comparison(packetDoc(late));
  const comparison=stage.p.app.openedModals.at(-1);await comparison.opened;
  const comparisonContent=comparison.contentEl;
  assert(find(comparisonContent,'summary','查看差异'));
  const remote=find(comparisonContent,'summary','OldOnly.md').parentNode;
  assert(button(remote,'打开同步空间'));
  const remoteTab=comparisonContent.querySelectorAll('button').find(x=>x.textContent.startsWith('对端独有 '));
  await click(remoteTab);
  const [sendFooter,remoteFooter]=footers(comparisonContent);
  assert(sendFooter.hidden&&!remoteFooter.hidden);
  assert(!button(remoteFooter,'打开同步空间').hidden);
  selectedRadio(comparisonContent,'OldOnly.md');
  await click(button(remoteFooter,'本次忽略'));
  assert(!find(comparisonContent,'summary','OldOnly.md'));
  await click(button(comparisonContent,'显示已忽略（1）'));
  await click(button(comparisonContent,'恢复显示'));
  assert(find(comparisonContent,'summary','OldOnly.md'));
  const conflictOnly=await host(Mobile,B,'Discard last entry');
  await conflictOnly.write('Only.md','local content');
  const loneSender=await host(Windows,A,'Single conflict');
  await loneSender.write('Only.md','remote content');
  const single=await publish(loneSender);
  await receive(conflictOnly,single,false);
  const lonePlan=await checkedPlan(conflictOnly),item=lonePlan.items[0];
  assert.equal(item.status,'conflict');
  assert.equal((await conflictOnly.p.v608DiscardReviewVersion(lonePlan,item.recordId,item.version)).cleanupPending,false);
  assert(!conflictOnly.p.v605HasPending());
  assert(!await conflictOnly.adapter.exists('VaultRelay-Transfer/inbox/'+single.rec.name));
  assert.equal(await conflictOnly.adapter.read('Only.md'),'local content');
  const multiSource=await host(Windows,A,'Two conflicts'),multiTarget=await host(Mobile,B,'Multi select');
  await multiSource.write('First.md','remote one');await multiSource.write('Second.md','remote two');
  await multiTarget.write('First.md','local one');await multiTarget.write('Second.md','local two');
  const multiPacket=await publish(multiSource);await receive(multiTarget,multiPacket,false);
  const multiReview=await openReview(multiTarget),multiContent=multiReview.contentEl;
  await settle(()=>find(multiContent,'button','待处理 2'));
  await click(button(multiContent,'待处理 2'));
  const multiChecks=multiContent.querySelectorAll('input').filter(x=>(x.getAttribute('aria-label')||'').startsWith('选择 '));
  assert.equal(multiChecks.length,2);
  const multiAll=multiContent.querySelectorAll('.vr607-tools')[0].querySelectorAll('input')[0];
  multiAll.checked=true;multiAll.onchange();assert(multiChecks.every(x=>x.checked));
  multiAll.checked=false;multiAll.onchange();assert(multiChecks.every(x=>!x.checked));
  selectCheckbox(checkbox(multiContent,'First.md'),true);
  selectCheckbox(checkbox(multiContent,'Second.md'),true,{shiftKey:true});
  assert(multiChecks.every(x=>x.checked),'Shift should select the contiguous range');
  selectCheckbox(checkbox(multiContent,'First.md'),false,{ctrlKey:true});
  assert(!checkbox(multiContent,'First.md').checked&&checkbox(multiContent,'Second.md').checked);
  selectCheckbox(checkbox(multiContent,'Second.md'),false);
  assert(!multiChecks.some(x=>x.checked),'Click again should clear selection');
  const checks=['Windows 与移动端冲突行临时忽略可恢复，重开窗口重新显示，取消确认不留记录',
    '按确切版本放弃，拒绝过期预览，重启后仍有效，同包剩余条目导入前保留，处理后回收，重复下载不改本机内容',
    '早包不覆盖新正文，旧版本移入已跳过，缺正文提供补包与临时忽略，核对比对页同类操作','单条冲突确认放弃后可直接回收已处理的原包，本机正文保留',
    '分类切换显示对应页脚，待处理和对端独有操作只针对所选行，切回可导入保留勾选，缺正文可调用同步空间入口',
    '已跳过支持全选、单选与取消选择，明确确认后按版本持久隐藏；知识库比对显示 Win1 / Red1 简称',
    '待处理列表支持多项、全选、Shift 连选、Ctrl 点击追加及再次点击取消'];
  fs.writeFileSync(path.join(results,'v611-discard.json'),JSON.stringify({status:'PASS',checks},null,2)+'\n');
  console.log('PASS '+checks.length+' V6.10 regression groups');
}
run().catch(error=>{console.error(error);process.exitCode=1;});

