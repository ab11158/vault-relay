const assert=require('node:assert/strict');
const fs=require('node:fs');
const {Windows,Mobile,IOS,A,B,host,publish,receive}=require('./test-flow.cjs');
const api=Windows.__testing.v70.sealed;
const joinTrust=async(a,b)=>{
 const {card}=await api.readIdentity(b.p.data.v73Identity.publicId,a.p.data.groupId);
 return api.trust(a.p,card,await api.fingerprint(card));
};
(async()=>{
 const pc=await host(Windows,null,'Receiver',{}),phone=await host(Mobile,null,'Phone',{}),tablet=await host(IOS,null,'Tablet',{});
 const group=await pc.p.createGroup();
 for(const h of [phone,tablet]){await h.p.joinGroup(group);await h.p.updateSetting('groupShortName','Tes1');}
 await phone.write('Phone.md','phone content');
 const packet=await publish(phone),inbox='VaultRelay-Transfer/inbox/'+packet.rec.name;
 await assert.rejects(receive(pc,packet,false),/已拒收/);
 assert(!await pc.adapter.exists(inbox)); assert(!await pc.adapter.exists('Phone.md'));
 assert(await phone.adapter.exists(packet.rec.stored.path));
 await joinTrust(pc,phone);
 await assert.rejects(joinTrust(pc,tablet),/只能信任一台/);
 const preview=await pc.p.engine.latestPlan(); assert(!preview.items.some(i=>i.path==='Phone.md'));
 await receive(pc,packet);assert.equal(await pc.adapter.read('Phone.md'),'phone content');
 await phone.write('Late.md','late content');
 const late=await publish(phone),lateInbox='VaultRelay-Transfer/inbox/'+late.rec.name;
 await receive(pc,late,false);
 const oldReview=await pc.p.engine.latestPlan();
 await api.untrust(pc.p,phone.p.data.v73Identity.deviceId);await joinTrust(pc,tablet);
 await assert.rejects(pc.p.engine.applyPlan(oldReview,{selectedReviewPaths:['Late.md']}),/已拒收/);
 assert(!await pc.adapter.exists(lateInbox));assert(!await pc.adapter.exists('Late.md'));
 const after=await pc.p.engine.latestPlan();assert(!after.items.some(item=>item.path==='Late.md'), 'previously staged rejected package must not remain in the native review');
 await tablet.write('Tablet.md','tablet content');await receive(pc,await publish(tablet));
 assert.equal(await pc.adapter.read('Tablet.md'),'tablet content');
 await phone.write('Scan.md','scan content');const scan=await publish(phone);
 const path='VaultRelay-Transfer/inbox/'+scan.rec.name;await pc.adapter.writeBinary(path,scan.bytes);
 const settled=new Date(Date.now()-6000);fs.utimesSync(pc.abs(path),settled,settled);
 await pc.p.v604PrepareInbox();assert(!await pc.adapter.exists(path));
 assert(!await pc.adapter.exists('Scan.md'));assert(await phone.adapter.exists(scan.rec.stored.path));
 const ding=await host(IOS,null,'iPad reader',{});await ding.p.joinGroup(group);
 const DBOX='VaultRelay-Transfer/Dbox/';
 await ding.adapter.mkdir(DBOX.replace(/\/$/,''));
 const dboxPath=DBOX+scan.rec.name;await ding.adapter.writeBinary(dboxPath,scan.bytes);
 fs.utimesSync(ding.abs(dboxPath),settled,settled);
 const dbox=await ding.p.vrCollectDbox();assert(!await ding.adapter.exists(dboxPath),JSON.stringify(dbox));
 assert(!await ding.adapter.exists('VaultRelay-Transfer/inbox/'+scan.rec.name));
 const note='Restricted.md',senderId=phone.p.data.v73Identity.deviceId,receiverId=pc.p.data.v73Identity.deviceId;
 await joinTrust(phone,pc);
 await phone.write(note,'restricted body');
 phone.p.data.v70PrivateNotes={[JSON.stringify([group,senderId])]:{notes:[note],attachments:[],links:{},devices:{[note]:{in:[],out:[receiverId]}}}};
 await phone.p.persistTransport();
 const up=await phone.p.engine.previewUpload();assert(up.restricted.some(row=>row.path===note&&row.publishable));
 const prepared=await phone.p.engine.safeExport(up,{selectedPaths:[note],expectedFingerprint:up.fingerprint,allowInitial:true});
 await phone.p.finalizeConfirmedUpload(prepared);
 const privateRecord=phone.p.data.bundleRecords.at(-1);
 const sealed={rec:privateRecord,bytes:await phone.adapter.readBinary(privateRecord.stored.path)};
 await assert.rejects(receive(pc,sealed,false),/已拒收/);
 assert(!await pc.adapter.exists('VaultRelay-Transfer/inbox/'+privateRecord.name));
 await api.untrust(pc.p,tablet.p.data.v73Identity.deviceId);await joinTrust(pc,phone);
 await receive(pc,late);assert.equal(await pc.adapter.read('Late.md'),'late content');
 await receive(pc,sealed,false);
 const row=(await pc.p.v604PrepareInbox()).find(item=>item.sha256===privateRecord.sha256);
 const partial=Windows.__testing.v71.review.restrictedRows(pc.p,await pc.p.engine.latestPlan()).find(item=>item.path===note);
 assert(partial?.v71Sealed);
 await assert.rejects(pc.p.v70ConfirmSealed(row,partial.v71Sealed.item.index,'processed'),/允许/);
 pc.p.data.v70PrivateNotes={[JSON.stringify([group,receiverId])]:{notes:[note],attachments:[],links:{},devices:{[note]:{in:[senderId],out:[]}}}};
 await pc.p.persistTransport();
 await pc.p.v70ConfirmSealed(row,partial.v71Sealed.item.index,'processed');
 assert.equal(await pc.adapter.read(note),'restricted body');
 const legacySender=await host(Mobile,B,'Legacy sender'),legacyReceiver=await host(Windows,A,'Legacy receiver');
 await legacySender.write('Legacy.md','legacy unsigned content');
 const legacy=await publish(legacySender),legacyInbox='VaultRelay-Transfer/inbox/'+legacy.rec.name;
 await legacyReceiver.adapter.mkdir('VaultRelay-Transfer/inbox');
 await legacyReceiver.adapter.writeBinary(legacyInbox,legacy.bytes);
 fs.utimesSync(legacyReceiver.abs(legacyInbox),settled,settled);
 await legacyReceiver.p.v604PrepareInbox();
 assert(await legacyReceiver.adapter.exists(legacyInbox));
 assert(!await legacyReceiver.adapter.exists('Legacy.md'));
 console.log('PASS signed ordinary and restricted ZIP trust, local deletion, redownload, device rebind, Dbox and legacy handling');
})().catch(e=>{console.error(e);process.exitCode=1;});