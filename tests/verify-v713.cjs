'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {host,publish,receive,Windows,Mobile,IOS}=require('./test-flow.cjs');
const find=(root,label)=>root.querySelectorAll('button').find(x=>x.textContent===label);
const DBOX='VaultRelay-Transfer/Dbox/';
(async()=>{
  const sender=await host(Windows,null,'Sending',{}),note='Conflict.md';
  const gid=await sender.p.createGroup(),owner=sender.p.engine.state.deviceId;
  await sender.p.updateSetting('deviceShortName','Win1');
  await sender.p.saveDownloadDirectoryTarget('/First share');
  sender.p.data.groupName='共享资料测试';sender.p.data.groupShortName='Qat1';
  sender.p.data.shareUrl='https://pan.baidu.com/s/old?pwd=abcd';
  await sender.write(note,'Incoming\n');await sender.write('Other.md','Also pending\n');
  const packet=await publish(sender);
  const decoded=Windows.__testing.tools.zipDecode(packet.bytes);
  const doc=JSON.parse(Buffer.from(decoded.get('sync-inventory.json')).toString('utf8'));
  assert.equal(doc.sharedBasic.downloadPath,'/_pcs_.workspace/First share');
  assert(!JSON.stringify(doc.sharedBasic).includes('abcd'));
  for(const Type of [Windows,Mobile,IOS]){
    const target=await host(Type,null,'Receiving',{});
    await target.p.joinGroup(gid);await target.p.updateSetting('deviceShortName','Red1');
    await target.write(note,'Local\n');
    await receive(target,packet,false);
    assert.equal(target.p.data.downloadDirectoryTarget.path,doc.sharedBasic.downloadPath);
    assert.equal(target.p.data.groupName,'共享资料测试');
    assert.equal(target.p.data.groupShortName,'Qat1');
    assert.equal(target.p.data.deviceShortName,'Red1');
    assert(!target.p.data.shareUrl);
    assert.equal(target.p.data.vr713GroupOwner,owner);
    await target.p.v604PrepareInbox();
    const before=await target.p.engine.latestPlan();
    const item=before.items.find(x=>x.path===note);
    assert.equal(item.status,'conflict');
    const done=await target.p.vr713ResolveReviewConflict(before,item.recordId,item.version,{keepBackup:true});
    assert.equal(await target.adapter.read(note),'Incoming\n');
    assert.match(done.backup,/Conflict备份\.md$/);
    assert.equal(await target.adapter.read(done.backup),'Local\n');
    assert.notEqual(done.versionId,item.version.versionId);
    assert.equal(target.p.engine.state.known[note].versionId,done.versionId);
    const rows=await target.p.v604PrepareInbox();
    assert(rows.some(row=>row.sha256===packet.rec.sha256),'Other entries keep the ZIP in the queue');
    const remaining=await target.p.engine.latestPlan();
    assert(['history-only','discarded'].includes(remaining.items.find(x=>x.path===note)?.status));
    assert.equal(remaining.items.find(x=>x.path==='Other.md').status,'create');
  }
  const tablet=await host(IOS,null,'Tablet',{});await tablet.p.joinGroup(gid);
  const panel=new IOS.__testing.panel(tablet.p.app,tablet.p);
  panel.render=()=>{};tablet.p._vrControlPanel=panel;
  global.document={visibilityState:'visible',createElement:tag=>Object.assign(new panel.modalEl.constructor(tag),{dataset:{}})};
  await tablet.adapter.writeBinary(DBOX+packet.rec.name,packet.bytes);
  const old=new Date(Date.now()-7000);fs.utimesSync(tablet.abs(DBOX+packet.rec.name),old,old);
  await panel.searchDownloadZips();
  const scan=tablet.p._v5216ScanModal;
  assert(scan.value.files.some(f=>f.name===packet.rec.name));
  assert(find(scan.contentEl,'全盘扫描'));
  assert(!tablet.p._vrReviewModal);
  scan.close();
  await panel.refreshDownloadReview();
  const review=tablet.p._vrReviewModal;
  assert(find(review.contentEl,'全盘扫描'));
  assert(review._v71Selected.has(packet.rec.sha256));
  assert(!await tablet.adapter.exists(note));review.close();

  const sourceDir='Browser Downloads';
  await sender.p.saveDownloadDirectoryTarget('/Updated share');
  await sender.write('Folder test.md','Found only after full scan\n');
  const next=await publish(sender);
  await tablet.adapter.mkdir(sourceDir);
  await tablet.adapter.writeBinary(sourceDir+'/'+next.rec.name,next.bytes);
  fs.utimesSync(tablet.abs(sourceDir+'/'+next.rec.name),old,old);
  await panel.refreshDownloadReview();
  const existing=tablet.p._vrReviewModal;
  assert(!existing._v71Selected.has(next.rec.sha256));
  const beforeFull=tablet.p.app.openedModals.length;
  await find(existing.contentEl,'全盘扫描').click();
  assert.equal(tablet.p._vrReviewModal,existing);
  assert.equal(tablet.p.app.openedModals.length,beforeFull+1,'Full scan opens only its progress dialog');
  assert(existing._v71Selected.has(next.rec.sha256));
  assert.equal(tablet.p.data.downloadDirectoryTarget.path,'/_pcs_.workspace/Updated share');
  existing.close();
  await sender.write('Learned folder.md','Found by light scan\n');
  const third=await publish(sender);
  await tablet.adapter.writeBinary(sourceDir+'/'+third.rec.name,third.bytes);
  fs.utimesSync(tablet.abs(sourceDir+'/'+third.rec.name),old,old);
  await panel.refreshDownloadReview();
  assert(tablet.p._vrReviewModal._v71Selected.has(third.rec.sha256));
  await receive(tablet,packet,false);
  assert.equal(tablet.p.data.downloadDirectoryTarget.path,'/_pcs_.workspace/Updated share','Earlier signed pack cannot roll back the latest directory');
  tablet.p._vrReviewModal.close();
  const phone=await host(Mobile,null,'Phone',{});await phone.p.joinGroup(gid);
  const publicRoot='/storage/emulated/0/Download/';
  const baidu=publicRoot+'BaiduNetdisk/_pcs_.workspace/00Obsidian/VaultRelay-Transfer/';
  const firstFolder=baidu+'test2/';
  const otherFolder=publicRoot+'Other Download/Team/VaultRelay-Transfer/Notes/Incoming/';
  const vaultRoot=publicRoot+'Vault/';
  const anotherVault=publicRoot+'Another Vault/';
  const deviceDirs=new Map(),visited=new Set();
  phone.adapter.getBasePath=()=>vaultRoot.replace('/storage/emulated/0/','/sdcard/').slice(0,-1);
  phone.p.mobileCapacitorFilesystem=()=>({});
  phone.p.getMobileDownloadEntries=async uri=>{
    const dir=decodeURIComponent(new URL(uri).pathname);
    visited.add(dir);
    return [...(deviceDirs.get(dir)?.values()||[])];
  };
  const put=(folder,item)=>{
    let dir='/';
    for(const name of folder.split('/').filter(Boolean)){
      if(!deviceDirs.has(dir))deviceDirs.set(dir,new Map());
      deviceDirs.get(dir).set(name,{name,isDirectory:true});
      dir+=name+'/';
    }
    if(!deviceDirs.has(dir))deviceDirs.set(dir,new Map());
    if(item)deviceDirs.get(dir).set(item.rec.name,{name:item.rec.name,isFile:true,file:resolve=>resolve({
      size:item.bytes.byteLength,lastModified:old.getTime(),arrayBuffer:async()=>item.bytes
    })});
  };
  put(firstFolder,packet);put(otherFolder,next);
  put(vaultRoot+'VaultRelay-Transfer/internal/history/',third);
  put(anotherVault+'VaultRelay-Transfer/recovery/quarantine/',third);
  put(vaultRoot+'VaultRelay-Transfer/outgoing/',third);
  const excluded=anotherVault+'VaultRelay-Transfer/Outgoing/archive/';
  put(excluded,third);put(baidu+'outgoing/',third);
  phone.p.data.mobileExtraSources=[excluded];
  const initial=await phone.p.vr713ScanDownloads();
  assert.equal(initial.source.files.length,0,'Light scan must not walk unlearned folders');
  const full=await phone.p.vr713ScanDownloads({full:true});
  assert.deepEqual(full.source.files.filter(row=>!row.unavailable).map(x=>x.name).sort(),[packet.rec.name,next.rec.name].sort());
  const managed=full.source.files.filter(row=>row.unavailable);
  assert.equal(managed.length,2,'History and quarantine are listed without re-queueing their ZIPs');
  assert(managed.every(row=>row.name===third.rec.name&&!row.target));
  assert(!await phone.adapter.exists('VaultRelay-Transfer/inbox/'+third.rec.name));
  for(const dir of [vaultRoot+'VaultRelay-Transfer/outgoing/',anotherVault+'VaultRelay-Transfer/Outgoing/',excluded,baidu+'outgoing/'])assert(!visited.has(dir),dir);
  const pending=phone.p._vr713ChosenSources=new Map();
  const picked={group:gid,device:phone.p.engine.state.deviceId,origin:excluded+third.rec.name};
  pending.set(third.rec.sha256,picked);
  await phone.p.vr713RememberChosenSource({sha256:third.rec.sha256});
  assert(!phone.p.v5218RankedDirs().some(dir=>dir.includes('/Outgoing/')));
  assert(!pending.has(third.rec.sha256));
  for(const item of [packet,next])assert(await phone.adapter.exists('VaultRelay-Transfer/inbox/'+item.rec.name));
  assert(!await phone.adapter.exists(note),'Finding the package must not import a note');
  put(firstFolder,third);
  const learned=await phone.p.vr713ScanDownloads();
  assert(learned.source.files.some(x=>x.name===third.rec.name&&x.target==='VaultRelay-Transfer/inbox/'+third.rec.name));
  console.log('PASS Android full scan discovers varying download paths and excludes outgoing and preserves stored ZIPs; light scan reuses discovered paths');
  delete global.document;
  console.log('PASS shared settings, conflict version and local backup across 3 platforms; tablet Dbox light scan and review');
})().catch(error=>{console.error(error);process.exitCode=1;});
